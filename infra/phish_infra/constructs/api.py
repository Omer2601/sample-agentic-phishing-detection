ROUTES: list[tuple[str, str]] = [
    ("POST", "/scan"),
    ("GET", "/scans/lookup"),
    ("GET", "/scans/*"),
    ("GET", "/scans/*/report"),
    ("POST", "/scans/*/retry"),
    ("POST", "/batches"),
    ("GET", "/batches"),
    ("GET", "/batches/*"),
    ("GET", "/batches/*/report"),
    ("POST", "/batches/*/retry-failed"),
    ("GET", "/history"),
    ("GET", "/stats"),
    ("GET", "/stats/export"),
    ("GET", "/feed/phishing"),
    ("GET", "/health"),
]
S = apigw.JsonSchemaType

# Wording of contracts/phish_contracts/disclaimer.py DISCLAIMER_TEXT. Copied, not imported:
# `cdk.json` runs the app with `--package phish-infra`, whose environment does not include
# phish-contracts. tests/test_api_gateway_responses.py asserts the two stay equal.
DISCLAIMER_TEXT = (
    "This output was generated by AI and can be wrong. "
    "A qualified human analyst must review it before any action is taken."
)

# Errors API Gateway produces itself, before or instead of the Lambda. Each keeps its default
# status code and renders the Lambda's error envelope: `error` plus the top-level `disclaimer`.
GATEWAY_ERROR_TYPES: list[tuple[str, apigw.ResponseType]] = [
    ("BadRequestBody", apigw.ResponseType.BAD_REQUEST_BODY),
    ("BadRequestParameters", apigw.ResponseType.BAD_REQUEST_PARAMETERS),
    ("MissingAuthenticationToken", apigw.ResponseType.MISSING_AUTHENTICATION_TOKEN),
    ("AccessDenied", apigw.ResponseType.ACCESS_DENIED),
    ("Unauthorized", apigw.ResponseType.UNAUTHORIZED),
    ("InvalidSignature", apigw.ResponseType.INVALID_SIGNATURE),
    ("ExpiredToken", apigw.ResponseType.EXPIRED_TOKEN),
    ("Throttled", apigw.ResponseType.THROTTLED),
    ("ResourceNotFound", apigw.ResponseType.RESOURCE_NOT_FOUND),
    ("Default4xx", apigw.ResponseType.DEFAULT_4_XX),
    ("Default5xx", apigw.ResponseType.DEFAULT_5_XX),
]
# `$context.error.messageString` is substituted already JSON-quoted by API Gateway (the
# service's own default template is `{"message":$context.error.messageString}`), so it is not
# wrapped in quotes here. Quotes are escaped but control characters are not, and a template
# cannot escape them. The SigV4 errors carry a multi-line message that also echoes the
# canonical request back to the caller, so those types get a fixed message instead.
FIXED_GATEWAY_MESSAGES: dict[str, str] = {
    "InvalidSignature": (
        "The request signature does not match. Sign the request with SigV4 for service "
        "execute-api and the exact method, path, query and body sent."
    ),
    "ExpiredToken": "The security token included in the request has expired.",
}


def gateway_error_template(gw_id: str) -> str:
    """The error envelope for one gateway response type: {"error": ..., "disclaimer": ...}."""
    fixed = FIXED_GATEWAY_MESSAGES.get(gw_id)
    message = json.dumps(fixed) if fixed else "$context.error.messageString"
    return '{"error":' + message + ',"disclaimer":' + json.dumps(DISCLAIMER_TEXT) + "}"


class ScanApi(Construct):
    def __init__(
        self,
        scope: Construct,
        id: str,
        *,
        cfg: AppConfig,
        data: DataLayer,
        guardrails: Guardrails,
        pipeline: ScanPipeline,
        agents: AgentsLayer,
        backend_code: lambda_.Code,
        proxy_role_name: str,
    ) -> None:
        super().__init__(scope, id)
        stack = cdk.Stack.of(self)
        name, env = cfg.app_name, cfg.environment

        self.function = python_function(
            self,
            "Function",
            cfg=cfg,
            key=data.key,
            code=backend_code,
            handler="phish_backend.api.app.handler",
            description="Scan API: submit scans and batches, read results, history and stats",
            environment={
                **backend_environment(cfg, data, agents),
                "SCAN_QUEUE_URL": pipeline.queue.queue_url,
                "GUARDRAIL_INPUT_ID": guardrails.input_id,
                "GUARDRAIL_INPUT_VERSION": guardrails.input_version,
                "IDEMPOTENCY_TABLE": data.idempotency_table.table_name,
                "SCAN_DEDUP_ENABLED": "1" if cfg.scan_dedup else "0",
                # Requests signed by this role may carry X-Console-User-Sub (the Cognito sub).
                "PROXY_ROLE_ARN": (
                    f"arn:{stack.partition}:iam::{stack.account}:role/{proxy_role_name}"
                ),
            },
            timeout=cdk.Duration.seconds(30),
            memory_mb=512,
        )
        fn = self.function
        for table in (data.scans_table, data.batches_table):
            table.grant(
                fn,
                "dynamodb:GetItem",
                "dynamodb:PutItem",
                "dynamodb:UpdateItem",
                "dynamodb:Query",
                "dynamodb:BatchWriteItem",
            )
        # Idempotency-Key claims: read, conditional put, and release after a 503.
        data.idempotency_table.grant(
            fn, "dynamodb:GetItem", "dynamodb:PutItem", "dynamodb:DeleteItem"
        )
        # The stats read model fetches several buckets in one BatchGetItem.
        data.stats_table.grant(fn, "dynamodb:GetItem", "dynamodb:BatchGetItem", "dynamodb:Query")
        pipeline.queue.grant_send_messages(fn)
        # Presigned POST is signed with this role, so the role needs PutObject on the prefix.
        fn.add_to_role_policy(
            iam.PolicyStatement(
                actions=["s3:PutObject"],
                resources=[data.upload_bucket.arn_for_objects("uploads/*")],
            )
        )
        # HTML reports: the API renders them into the artifacts bucket, then presigns a GET.
        report_keys = [
            data.artifacts_bucket.arn_for_objects("scans/*/report.html"),
            data.artifacts_bucket.arn_for_objects("batches/*/report.html"),
        ]
        fn.add_to_role_policy(iam.PolicyStatement(actions=["s3:PutObject"], resources=report_keys))
        # Presigned GET for screenshots and reports, the only artifacts the API hands out.
        fn.add_to_role_policy(
            iam.PolicyStatement(
                actions=["s3:GetObject"],
                resources=[
                    data.artifacts_bucket.arn_for_objects("scans/*/screenshot.png"),
                    *report_keys,
                ],
            )
        )
        fn.add_to_role_policy(
            iam.PolicyStatement(
                actions=["bedrock:ApplyGuardrail"], resources=[guardrails.input_arn]
            )
        )
        data.key.grant_encrypt_decrypt(fn)

        access_logs = logs.LogGroup(
            self,
            "AccessLogs",
            log_group_name=f"/aws/apigateway/{name}-access-{env}",
            retention=logs.RetentionDays.ONE_YEAR,
            encryption_key=data.key,
            removal_policy=cfg.removal_policy,
        )
        health = "execute-api:/*/GET/health"
        self.rest_api = apigw.RestApi(
            self,
            "RestApi",
            rest_api_name=f"{name}-{env}",
            description="Phishing triage REST API (IAM auth)",
            endpoint_configuration=apigw.EndpointConfiguration(types=[apigw.EndpointType.REGIONAL]),
            cloud_watch_role=True,
            cloud_watch_role_removal_policy=cfg.removal_policy,
            # Only /health is allowed here. For IAM-authorized methods a same-account caller is
            # let in by its own identity policy (the web proxy role or a holder of
            # ApiInvokePolicy); a caller in another account would need an Allow in this resource
            # policy as well, which no method but /health has, so other accounts get nothing.
            policy=iam.PolicyDocument(
                statements=[
                    iam.PolicyStatement(
                        principals=[iam.AnyPrincipal()],
                        actions=["execute-api:Invoke"],
                        resources=[health],
                        conditions={"Bool": {"aws:SecureTransport": "true"}},
                    ),
                ]
            ),
            deploy_options=apigw.StageOptions(
                stage_name=env,
                # Batches arrive via S3, so API traffic is polling plus small writes. Throttled
                # requests get 429 and the web client retries them with backoff.
                throttling_rate_limit=50,
                throttling_burst_limit=100,
                logging_level=apigw.MethodLoggingLevel.INFO,
                metrics_enabled=True,
                data_trace_enabled=False,  # never log request or response bodies
                tracing_enabled=True,
                access_log_destination=apigw.LogGroupLogDestination(access_logs),
                access_log_format=apigw.AccessLogFormat.json_with_standard_fields(
                    caller=True,
                    http_method=True,
                    ip=True,
                    protocol=True,
                    request_time=True,
                    resource_path=True,
                    response_length=True,
                    status=True,
                    user=True,
                ),
            ),
        )
        # RestApi adds its own hashed "Endpoint" output; ApiUrl below is the interface name.
        self.rest_api.node.try_remove_child("Endpoint")
        # Built from the RestApi id rather than rest_api.url: the URL token pulls in the
        # deployment and every method, which would make the console (whose origin the upload
        # bucket CORS rule needs) depend on the API role and so on the upload bucket: a cycle.
        self.base_url = (
            f"https://{self.rest_api.rest_api_id}.execute-api.{stack.region}"
            f".{stack.url_suffix}/{env}/"
        )
        body_validator = self.rest_api.add_request_validator(
            "Body", validate_request_body=True, validate_request_parameters=True
        )
        param_validator = self.rest_api.add_request_validator(
            "Params", validate_request_parameters=True
        )
        url = apigw.JsonSchema(type=S.STRING, min_length=1, max_length=2048)
        scan_model = self.rest_api.add_model(
            "ScanModel",
            content_type="application/json",
            model_name="ScanRequest",
            schema=apigw.JsonSchema(
                schema=apigw.JsonSchemaVersion.DRAFT4,
                type=S.OBJECT,
                required=["url"],
                properties={"url": url, "force": apigw.JsonSchema(type=S.BOOLEAN)},
                additional_properties=False,
            ),
        )
        batch_model = self.rest_api.add_model(
            "BatchModel",
            content_type="application/json",
            model_name="BatchRequest",
            schema=apigw.JsonSchema(
                schema=apigw.JsonSchemaVersion.DRAFT4,
                type=S.OBJECT,
                additional_properties=False,
                properties={
                    "urls": apigw.JsonSchema(type=S.ARRAY, min_items=1, max_items=50, items=url),
                    "upload": apigw.JsonSchema(type=S.BOOLEAN),
                    "count": apigw.JsonSchema(type=S.INTEGER, minimum=1, maximum=1000),
                    "source": apigw.JsonSchema(type=S.STRING, enum=["ui", "api"]),
                },
            ),
        )

        # Same headers the Lambda sets on its own responses (backend api/http.py).
        error_headers = {
            "Content-Type": "'application/json'",
            "Cache-Control": "'no-store'",
            "X-Content-Type-Options": "'nosniff'",
        }
        for gw_id, response_type in GATEWAY_ERROR_TYPES:
            self.rest_api.add_gateway_response(
                f"{gw_id}Response",
                type=response_type,
                response_headers=error_headers,
                templates={"application/json": gateway_error_template(gw_id)},
            )

        integration = apigw.LambdaIntegration(fn, proxy=True)
        # The Python binding takes method options as keyword arguments.
        iam_get = {
            "authorization_type": apigw.AuthorizationType.IAM,
            "request_validator": param_validator,
        }

        def post(model: apigw.IModel) -> dict:
            return {
                "authorization_type": apigw.AuthorizationType.IAM,
                "request_validator": body_validator,
                "request_models": {"application/json": model},
            }

        root = self.rest_api.root
        root.add_resource("scan").add_method("POST", integration, **post(scan_model))
        # Path parameter is {id} everywhere: the backend router keys on the resource string.
        scans = root.add_resource("scans")
        # A static segment is matched before {id}, so /scans/lookup never reaches GET /scans/{id}.
        # url and include_failed are validated by the Lambda, which answers with its own 400.
        scans.add_resource("lookup").add_method("GET", integration, **iam_get)
        scan = scans.add_resource("{id}")
        scan.add_method("GET", integration, **iam_get)
        scan.add_resource("report").add_method("GET", integration, **iam_get)
        scan.add_resource("retry").add_method("POST", integration, **iam_get)
        batches = root.add_resource("batches")
        batches.add_method("POST", integration, **post(batch_model))
        batches.add_method("GET", integration, **iam_get)
        batch = batches.add_resource("{id}")
        batch.add_method("GET", integration, **iam_get)
        batch.add_resource("report").add_method("GET", integration, **iam_get)
        batch.add_resource("retry-failed").add_method("POST", integration, **iam_get)
        root.add_resource("history").add_method("GET", integration, **iam_get)
        stats = root.add_resource("stats")
        stats.add_method("GET", integration, **iam_get)
        stats.add_resource("export").add_method("GET", integration, **iam_get)
        root.add_resource("feed").add_resource("phishing").add_method("GET", integration, **iam_get)
        # Liveness probe: no auth, returns {"ok": true} and nothing else.
        root.add_resource("health").add_method(
            "GET",
            integration,
            authorization_type=apigw.AuthorizationType.NONE,
            request_validator=param_validator,
        )

        self.invoke_policy = iam.ManagedPolicy(
            self,
            "InvokePolicy",
            managed_policy_name=f"{name}-api-invoke-{env}",
            description="Invoke every route of the phishing triage API with SigV4",
            statements=[
                iam.PolicyStatement(
                    actions=["execute-api:Invoke"],
                    resources=[
                        self.rest_api.arn_for_execute_api(method, path, env)
                        for method, path in ROUTES
                    ],
                )
            ],
        )

        action = cw_actions.SnsAction(data.alarm_topic)
        five = cdk.Duration.minutes(5)

        def alarm(
            id_: str,
            alarm_name: str,
            description: str,
            metric: cloudwatch.IMetric,
            threshold: float,
        ) -> None:
            cloudwatch.Alarm(
                self,
                id_,
                alarm_name=f"{name}-{alarm_name}-{env}",
                alarm_description=description,
                metric=metric,
                threshold=threshold,
                evaluation_periods=1,
                comparison_operator=cloudwatch.ComparisonOperator.GREATER_THAN_THRESHOLD,
                treat_missing_data=cloudwatch.TreatMissingData.NOT_BREACHING,
            ).add_alarm_action(action)

        alarm(
            "Api4xx",
            "api-4xx",
            "High 4XX rate: possible auth abuse or scanning",
            self.rest_api.metric_client_error(period=five, statistic="Sum"),
            50,
        )
        alarm(
            "Api5xx",
            "api-5xx",
            "High 5XX rate: service errors",
            self.rest_api.metric_server_error(period=five, statistic="Sum"),
            10,
        )
        for id_, status, metric_name, alarm_name, threshold, description in (
            (
                "AuthFailures",
                403,
                "AuthorizationFailures",
                "auth-failures",
                20,
                "High rate of 403 responses: possible unauthorized access attempts",
            ),
            (
                "UnauthAccess",
                401,
                "UnauthenticatedAccess",
                "unauth-access",
                10,
                "Unauthenticated requests (401): possible scanning or a misconfigured client",
            ),
        ):
            metric_filter = logs.MetricFilter(
                self,
                f"{id_}Filter",
                log_group=access_logs,
                filter_pattern=logs.FilterPattern.literal(f"{{ $.status = {status} }}"),
                metric_namespace=f"{name}/Security",
                metric_name=metric_name,
                metric_value="1",
            )
            alarm(
                id_,
                alarm_name,
                description,
                metric_filter.metric(period=five, statistic="Sum"),
                threshold,
            )

        stack_output(self, "ApiUrl", self.rest_api.url, "Scan API base URL (SigV4)")
        stack_output(
            self,
            "ApiInvokePolicyArn",
            self.invoke_policy.managed_policy_arn,
            "Attach to a role or user that calls the API directly",
        )
