import { describe, expect, it, vi } from "vitest";
import { render, screen } from "@testing-library/react";
import { MemoryRouter } from "react-router-dom";
import { ThemeProvider } from "@/hooks/useTheme";

vi.mock("@/hooks/useActiveBatches", () => ({
  useActiveBatches: () => ({
    batches: [],
    active: [],
    loaded: true,
    error: null,
    refresh: vi.fn(),
  }),
}));

import { AppShell, SIGN_OUT_PATH } from "./AppShell";

function renderShell() {
  return render(
    <ThemeProvider>
      <MemoryRouter>
        <AppShell>
          <p>page</p>
        </AppShell>
      </MemoryRouter>
    </ThemeProvider>,
  );
}

describe("AppShell sign out", () => {
  it("targets the server logout route", () => {
    expect(SIGN_OUT_PATH).toBe("/auth/logout");
  });

  it("renders a keyboard-reachable Sign out link in the header", () => {
    renderShell();
    const link = screen.getByRole("link", { name: "Sign out" });
    // A real href, not a client-side route: the server has to clear the
    // HttpOnly session cookie and end the Cognito session, which the SPA cannot.
    expect(link.getAttribute("href")).toBe("/auth/logout");
    expect(link.closest("header")).not.toBeNull();
    expect(link.getAttribute("tabindex")).not.toBe("-1");
    link.focus();
    expect(document.activeElement).toBe(link);
  });

  it("shows the persistent AI disclaimer banner under the header", () => {
    renderShell();
    const banner = screen.getByTestId("disclaimer-banner");
    expect(banner.getAttribute("role")).toBe("note");
    expect(banner.textContent).toContain(
      "AI-generated analysis: human review required",
    );
    expect(banner.textContent).toContain(
      "This output was generated by AI and can be wrong.",
    );
    const header = document.querySelector("header") as HTMLElement;
    expect(
      header.compareDocumentPosition(banner) & Node.DOCUMENT_POSITION_FOLLOWING,
    ).toBeTruthy();
    expect(header.contains(banner)).toBe(false);
  });

  it("uses theme tokens so it reads in light and dark mode", () => {
    renderShell();
    const cls = screen.getByRole("link", { name: "Sign out" }).className;
    expect(cls).toContain("text-fg-subtle");
    expect(cls).toContain("hover:text-fg");
    // Keyboard focus comes from the global :focus-visible ring in index.css.
    expect(cls).toContain("border-border");
    expect(cls).toContain("bg-surface");
  });
});

describe("AppShell layout", () => {
  // jsdom has no layout, so this pins the classes that give the sidebar a
  // background as tall as the page (UI e2e run 2, D9): a fixed, viewport-high
  // aside stopped at the first screen in full-page screenshots.
  it("fills at least the viewport and lets the sidebar column grow with the page", () => {
    const { container } = renderShell();
    const shell = container.firstElementChild as HTMLElement;
    expect(shell.className).toMatch(/\bmin-h-screen\b/);
    expect(shell.className).toMatch(/\blg:flex\b/);

    const aside = screen.getByRole("complementary");
    const column = aside.parentElement as HTMLElement;
    expect(column.parentElement).toBe(shell);
    // The column carries the background and stretches with the flex row.
    expect(column.className).toMatch(/\bbg-surface\/60\b/);
    expect(column.className).toMatch(/\bborder-r\b/);
    expect(column.className).not.toMatch(/\bfixed\b/);
    // The nav itself stays on screen while the page scrolls.
    expect(aside.className).toMatch(/\bsticky\b/);
    expect(aside.className).toMatch(/\bh-screen\b/);
  });
});

describe("AppShell brand", () => {
  it("shows the short product name and none of the retired one", () => {
    renderShell();
    expect(screen.getAllByText("Multi-Agent Phishing URL Detection").length).toBeGreaterThan(0);
    expect(document.body.textContent ?? "").not.toMatch(/phish\s*-?\s*guard\b/i);
  });
});
